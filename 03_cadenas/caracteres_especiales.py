# Para agregar caracteres especiales en las cadenas de texto de Python utilizamos el símbolo 'Backslash' \

# Comillas dobles dentro de comillas dobles:
mensaje = "Ella dijo \"Hola\" al entrar"
print("*** Comillas dobles ***")
print(mensaje,)
# Comilla simple:
print("\n*** Comilla sencilla ***")
print('Jose O\'Gorman')
# Nueva linea \n
print("\n*** Salto de linea ***")
print("Hola\nMundo")
# tabulacion \t
print("\n*** tabulacion ***")
print("Nombre:\tProgramador")
# Barra invertida \\
ruta = "C:\\Usuario\\Aiden\\Documentos"
print("\n*** Barra invertida ***")
print(ruta)
# Cadenas crudas o (raw string) r
print("\n*** Cadenas crudas ***")
ruta1 = r"C:\Usuario\Aiden\Documentos"
print(ruta1)