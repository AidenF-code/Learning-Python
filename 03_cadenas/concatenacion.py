"""
Concatenación en Python:
La concatenación en Python es el proceso de unir dos o más cadenas para formar una sola secuencia logica
"""
# Concatenación mediante el operador +
saludo = "Hola"
nombre = "Andres"
edad = 20
print(saludo +" "+ nombre)

# Método print()
print(saludo, nombre, "tienes", edad)
# Método F-String
print(f"Hola {nombre}, tienes {edad + 11}")
# El método F-String nos permite realizar algunas operaciones dentro de la cadena